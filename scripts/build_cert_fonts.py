#!/usr/bin/env python3
"""
Download certificate fonts (latin subset only) from Google Fonts
and generate a self-hosted CSS file with base64 data URIs.
Output: cloudflare-pages-site/assets/fonts/cert-fonts.css
Also downloads the raw .woff2 files to assets/fonts/cert/
"""

import re
import os
import sys
import base64
import urllib.request

FONTS_DIR = r"d:\Drafts\Blogs\website\cloudflare-pages-site\assets\fonts\cert"
OUT_CSS = r"d:\Drafts\Blogs\website\cloudflare-pages-site\assets\fonts\cert-fonts.css"
CSS_CACHE = os.path.join(FONTS_DIR, "google-fonts-response.css")

os.makedirs(FONTS_DIR, exist_ok=True)

# Parse @font-face blocks from the fetched CSS
with open(CSS_CACHE, encoding="utf-8") as f:
    css = f.read()

# Split into @font-face blocks
blocks = re.findall(r'@font-face\s*\{([^}]+)\}', css, re.DOTALL)
print(f"Total @font-face blocks: {len(blocks)}")

def parse_block(block):
    """Extract fields from a @font-face block."""
    family = re.search(r"font-family:\s*'?([^;']+)'?;", block)
    weight = re.search(r"font-weight:\s*(\d+)\s*;", block)
    style = re.search(r"font-style:\s*(\w+)\s*;", block)
    url = re.search(r"url\(([^)]+\.woff2)\)", block)
    unicode_range = re.search(r"unicode-range:\s*([^;]+);", block)
    return {
        "family": family.group(1).strip() if family else "",
        "weight": weight.group(1).strip() if weight else "400",
        "style": style.group(1).strip() if style else "normal",
        "url": url.group(1).strip() if url else "",
        "unicode_range": unicode_range.group(1).strip() if unicode_range else "",
    }

# The certificate uses these fonts:
CERT_FONTS = {"Outfit", "Space Grotesk", "JetBrains Mono", "Kalam", "Inter"}

# We want these specific weights per font:
CERT_WEIGHTS = {
    "Outfit": {"400", "500", "600", "700", "800", "900"},
    "Space Grotesk": {"500", "700", "900"},
    "JetBrains Mono": {"400", "600", "700", "800"},
    "Kalam": {"400", "700"},
    "Inter": {"400", "500", "600", "700", "800"},
}

# Latin unicode range - matches the last @font-face block per weight (the "latin" block)
# The latin block typically has: U+0000-00FF, U+0131, etc.
LATIN_MARKER = "U+0000-00FF"

def is_latin(unicode_range):
    return LATIN_MARKER in unicode_range

parsed = [parse_block(b) for b in blocks]
print(f"Parsed {len(parsed)} blocks")

# Filter to only the fonts and weights we need, latin subset only
wanted = []
for p in parsed:
    if p["family"] not in CERT_FONTS:
        continue
    if p["weight"] not in CERT_WEIGHTS.get(p["family"], set()):
        continue
    if not p["url"]:
        continue
    if not is_latin(p["unicode_range"]):
        continue
    wanted.append(p)

print(f"Filtered to {len(wanted)} latin font faces")
for w in wanted:
    print(f"  {w['family']} {w['weight']} {w['style']}")

# Download each woff2 and encode to base64
ua_headers = {"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/120.0.0.0 Safari/537.36"}

css_out_lines = [
    "/* Self-hosted certificate fonts — latin subset only",
    " * Auto-generated by build_cert_fonts.py — DO NOT EDIT",
    " * Fonts: Outfit, Space Grotesk, JetBrains Mono, Kalam, Inter",
    " */",
    ""
]

for p in wanted:
    url = p["url"]
    fname = url.split("/")[-1] + f"_{p['family'].replace(' ','_')}_{p['weight']}.woff2"
    fpath = os.path.join(FONTS_DIR, fname)
    
    if not os.path.exists(fpath):
        print(f"  Downloading: {p['family']} {p['weight']} ...")
        try:
            req = urllib.request.Request(url, headers=ua_headers)
            with urllib.request.urlopen(req, timeout=30) as resp:
                data = resp.read()
            with open(fpath, "wb") as f:
                f.write(data)
            print(f"    Saved {len(data)} bytes -> {fname}")
        except Exception as e:
            print(f"    ERROR downloading {url}: {e}")
            continue
    else:
        print(f"  Already have: {fname}")
        with open(fpath, "rb") as f:
            data = f.read()
    
    b64 = base64.b64encode(data).decode("ascii")
    data_uri = f"data:font/woff2;base64,{b64}"
    
    css_out_lines.append(f"@font-face {{")
    css_out_lines.append(f"  font-family: '{p['family']}';")
    css_out_lines.append(f"  font-style: {p['style']};")
    css_out_lines.append(f"  font-weight: {p['weight']};")
    css_out_lines.append(f"  font-display: swap;")
    css_out_lines.append(f"  src: url('{data_uri}') format('woff2');")
    css_out_lines.append(f"}}")
    css_out_lines.append(f"")

css_content = "\n".join(css_out_lines)
with open(OUT_CSS, "w", encoding="utf-8") as f:
    f.write(css_content)

size_kb = os.path.getsize(OUT_CSS) // 1024
print(f"\nWrote {OUT_CSS}")
print(f"File size: {size_kb} KB")
print("Done!")
